"""Import the two supplied MuPi action sheets and their JSON for the 800x480 game."""
import argparse
import json
from pathlib import Path
from PIL import Image

APP = Path(__file__).resolve().parents[1] / "examples/mupi-run"
COLS, ROWS = 10, 6
PER_PAGE = COLS * ROWS


def main(source):
    atlas = json.loads((source / "MuPi_Aktionen.json").read_text())
    result = {}
    for name, action in atlas["actions"].items():
        image = Image.open(source / action["image"]).convert("RGBA")
        width, height = action["contentPixels"]
        gutter = action["gutter"]
        # The character occupies about 205 logical screen pixels at native display size.
        scale = min(200 / width, 224 / height)
        size = tuple(round(scale * edge) for edge in (width, height))
        cell = tuple(edge + 2 for edge in size)
        for page in range(3):
            packed = Image.new("RGBA", (COLS * cell[0], ROWS * cell[1]))
            for index in range(PER_PAGE):
                tile = page * PER_PAGE + index
                x = tile % action["columns"] * action["cellWidth"] + gutter
                y = tile // action["columns"] * action["cellHeight"] + gutter
                sprite = image.crop((x, y, x + width, y + height)).resize(size, Image.Resampling.LANCZOS)
                packed.paste(sprite, (index % COLS * cell[0] + 1, index // COLS * cell[1] + 1))
            packed.save(APP / "art" / f"{name}-{page}.webp", quality=89, method=4)
        result[name] = dict(size=size, cell=cell, origin=action["origin"],
                            draw=[action["drawWidth"], action["drawHeight"]],
                            clips=[c["tiles"] for c in action["clipByRunFrame"]],
                            resume=[c["resumeRunFrame"] for c in action["clipByRunFrame"]])
    payload = dict(fps=atlas["fps"], frames=atlas["durationFrames"], columns=COLS, perPage=PER_PAGE, actions=result)
    (APP / "poses.js").write_text("// Generated by tools/import_mupi_run_actions.py\nwindow.MuPiPoses = " +
                                 json.dumps(payload, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="directory of the extracted MuPi_Sprung_und_Graetsche.zip")
    main(parser.parse_args().source)
