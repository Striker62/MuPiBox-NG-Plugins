"""Package first-party runner *media* and a validated scene selector.

Run build_mupi_run_native.py first. --host writes the reviewed runtime sources
to a MuPiBox-NG checkout at development time. Installed packages contain no code.
"""
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import wave
from zipfile import ZipFile, ZipInfo, ZIP_DEFLATED
from PIL import Image

root = Path(__file__).resolve().parents[1]
src = root / "examples/mupi-run"
build = root / "dist/mupi-run-native"
parser = argparse.ArgumentParser()
parser.add_argument("--host", type=Path)
args = parser.parse_args()
manifest = json.loads((src / "manifest.json").read_text())
manifest.update(id="community.mupi-run-native", name="MuPi Run · Qt Preview",
                version="0.1.0", runtime="qtquick-scene", entry="scene.json")
scene = dict(sceneVersion=1, engine="mupi-run-v1", background="#122b35", elements=[])
files = {name: (src / name) for name in ["cover.png", "icon.png", "AUDIO-CREDITS.txt"]}
# Preserve the Web loop sample-for-sample, including its loop length.
pcm = subprocess.check_output(["ffmpeg", "-v","error","-nostdin","-i",
    str(src / "assets/audio/music.ogg"), "-ac","1","-ar","48000","-f","s16le","pipe:1"])
music = build / "music.wav"
with wave.open(str(music),"wb") as out:
    out.setparams((1,2,48000,0,"NONE","not compressed"))
    out.writeframes(pcm)
files["assets/audio/music.wav"] = music
for path in sorted((src / "assets/audio").glob("*.wav")):
    files["assets/audio/" + path.name] = path
unused = {"ground-boardwalk.png","ground-forest.png","ground-river.png","logo-ui.png",
          "backdrop.png","foreground.png"}
for path in sorted((build / "assets").glob("*.png")):
    if path.name not in unused:
        files["assets/" + path.name] = path
if args.host:
    folder = args.host / "ui/qtquick/game/runner"
    folder.mkdir(exist_ok=True)
    for name in ("MuPiRunNative.qml", "RunWorld.js", "RunLogic.js", "RunTiles.js",
                 "RunPoses.js", "road.frag.qsb"):
        shutil.copyfile(build / name, folder / name)
    rows = []
    for name, path in sorted(files.items()):
        if path.suffix == ".png":
            with Image.open(path) as im:
                rows.append(f'\t"{name}": {{{im.width}, {im.height}}},')
    (args.host / "internal/pluginapps/runner_art.go").write_text(
        "// Code generated by package_mupi_run_scene.py. DO NOT EDIT.\npackage pluginapps\n\n"
        + "var runnerArt = map[string][2]int{\n" + "\n".join(rows) + "\n}\n")
target = root / "dist/mupi-run-native-preview.mupiapp"
with ZipFile(target, "w") as bundle:
    resources = {k: v.read_bytes() for k, v in files.items()}
    resources["AUDIO-CREDITS.txt"] += b"\nNative preview: the credited music loop was decoded to 48 kHz mono PCM WAV.\n"
    resources["scene.json"] = json.dumps(scene).encode()
    resources["manifest.json"] = json.dumps(manifest, ensure_ascii=False).encode()
    for name, data in sorted(resources.items()):
        member = ZipInfo(name, (2026,1,1,0,0,0))
        member.external_attr = 0o100644 << 16
        bundle.writestr(member, data, compress_type=ZIP_DEFLATED)
print(target, target.stat().st_size)

